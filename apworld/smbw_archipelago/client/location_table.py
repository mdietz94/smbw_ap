def lookup_name(check: CheckEmitted) -> str | None:
    """Resolve a CheckEmitted to its canonical AP location name.

    Returns ``None`` when no mapping exists; the caller (ap_client)
    should log + drop.  Missing entries are normal early in M4 (most
    courses haven't been mapped yet) and should NOT cascade into an AP
    error -- the bridge stays connected and the player just doesn't
    get credit for the un-mapped course until the table extends.
    """
    if check.kind == CheckKind.TEN_COIN:
        idx = int(check.metadata.get("coin_index", 0))
        name = _TEN_COIN_TABLE.get((check.stage_key, idx))
        if name is None:
            log.debug(
                "location_table: no AP location for ten_coin stage_key=%d index=%d",
                check.stage_key, idx)
        return name

    if check.kind == CheckKind.SHOP_SEED:
        world_no = int(check.metadata.get("world_no", 0))
        npc_id = int(check.metadata.get("npc_id", 0))
        item_value = int(check.metadata.get("item_value", 0))
        # Exact match wins.
        name = _SHOP_SEED_TABLE.get((world_no, npc_id, item_value))
        if name is not None:
            return name
        # Wildcard fallback for worlds where elimination uniquely
        # identifies the AP location (PI West, W5 Poplin, W6 Poplin).
        name = _SHOP_SEED_WILDCARD_TABLE.get((world_no, item_value))
        if name is None:
            log.debug(
                "location_table: no AP location for shop_seed "
                "(world=%d, npc=%d, item_value=%d) — add an entry to "
                "_SHOP_SEED_TABLE or _SHOP_SEED_WILDCARD_TABLE in "
                "location_table.py", world_no, npc_id, item_value)
        return name

    name = _TABLE.get((check.kind, check.stage_key))
    if name is None:
        log.debug(
            "location_table: no AP location for kind=%s stage_key=%d",
            check.kind.value, check.stage_key)
    return name
