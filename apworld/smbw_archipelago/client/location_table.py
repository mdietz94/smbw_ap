"""(CheckKind, stage_key) -> AP location name table.

The processor emits ``CheckEmitted(kind, stage_key, ...)``; this table
turns those into the canonical AP location strings the multiworld
server expects.  Name resolution to numeric AP IDs happens via the
connected ``CommonContext.location_names_to_id`` at lookup time.

Full coverage as of 2026-05-25: 142 courses captured via a single-pass
playtest sweep (see ``docs/playtest-stage-key-sweep.md``) and processed
by ``scripts/build_location_table.py``.  Poplin shops were intentionally
skipped during the sweep since they don't emit their own ``course_in``
events -- those stay un-mapped until verified by re-entry.

Location names must match ``apworld/smbw_archipelago/data/locations.json``
character-for-character.  To regenerate, re-run the playtest sweep and
the build script.

The table is checked in (not generated from the apworld at import time)
because ``stage_key`` is an SMBW runtime value with no other source of
truth, and the bridge should run from a plain venv without Archipelago's
full custom_worlds loader.
"""

